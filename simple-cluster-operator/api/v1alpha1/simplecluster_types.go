// SimpleClusterSpec defines the desired state of SimpleCluster.
type SimpleClusterSpec struct {
	// ControlPlane describes the control-plane pool. Optional: providers like
	// Gardener manage the CP themselves and ignore this. When set, exposed as
	// .SC.controlPlane.{nodes,requested.{cpu,memory}} in templates.
	// +optional
	ControlPlane *ControlPlaneSpec `json:"controlPlane,omitempty"`

	// Workers describes the worker pool sizing and per-worker resources.
	// Exposed to templates as .SC.workers.{nodes,requested.{cpu,memory}}.
	Workers WorkersSpec `json:"workers"`

	// ProviderConfigRefs is the ordered list of SCPC candidates by name. The
	// operator picks one and records the choice in status.providerConfigRef;
	// the locked choice is then immune to spec edits. v0.x picks the first
	// entry; future revisions will probe SCPC reachability/capacity.
	// +kubebuilder:validation:MinItems=1
	ProviderConfigRefs []string `json:"providerConfigRefs"`

	// Inputs are per-cluster overrides. Every key MUST be declared in
	// SCPC.spec.inputs; unknown keys are rejected. Keys left unset fall back
	// to the SCPC declaration's default.
	// +optional
	Inputs map[string]string `json:"inputs,omitempty"`

	// KubeconfigValidity overrides SCPC.kubeconfigSource.validity for this SC.
	// +optional
	KubeconfigValidity *metav1.Duration `json:"kubeconfigValidity,omitempty"`

	// KubeconfigRenewalBefore overrides SCPC.kubeconfigSource.renewalBefore for this SC.
	// +optional
	KubeconfigRenewalBefore *metav1.Duration `json:"kubeconfigRenewalBefore,omitempty"`

	// Resources are manifests applied to the provisioned cluster once it is
	// Ready, using the synced kubeconfig. Best-effort add-ons: each one's
	// outcome is reported in a status condition of type "Resource-<name>",
	// and a failure to apply never blocks Phase=Ready.
	// +optional
	// +listType=map
	// +listMapKey=name
	Resources []ClusterResource `json:"resources,omitempty"`
}

// ClusterResource is a raw manifest applied to the cluster a SimpleCluster
// provisions, after it becomes Ready.
type ClusterResource struct {
	// Name identifies this resource and is used as the suffix of its apply
	// condition ("Resource-<name>"). Must be DNS-label-safe.
	// +kubebuilder:validation:MinLength=1
	// +kubebuilder:validation:Pattern=`^[a-z0-9]([-a-z0-9]*[a-z0-9])?$`
	Name string `json:"name"`

	// Content is a single Kubernetes object manifest as YAML. apiVersion,
	// kind and metadata.name are required.
	// +kubebuilder:validation:MinLength=1
	Content string `json:"content"`
}

// ControlPlaneSpec describes the control-plane node pool.
type ControlPlaneSpec struct {
	// Nodes is the control-plane node count. Typical values: 1 (dev), 3 (HA).
	// Surfaced as .SC.controlPlane.nodes.
	// +kubebuilder:validation:Minimum=1
	// +kubebuilder:validation:Maximum=10
	Nodes int32 `json:"nodes"`

	// Requested is the per-node resource ask. Templates translate this to
	// a machine type / VM size / flavor.
	Requested NodeResources `json:"requested"`
}

// WorkersSpec describes the worker pool size and per-worker resource ask.
type WorkersSpec struct {
	// Nodes is the worker count. Surfaced as .SC.workers.nodes.
	// +kubebuilder:validation:Minimum=1
	// +kubebuilder:validation:Maximum=100
	Nodes int32 `json:"nodes"`

	// Requested is the per-worker resource ask. Templates surface these as
	// the worker machine type / VM size / replica resources.
	Requested NodeResources `json:"requested"`
}

// NodeResources is the per-node resource ask, shared by ControlPlaneSpec and
// WorkersSpec.
type NodeResources struct {
	// CPU is the requested CPU per node (e.g. "16", "500m").
	CPU resource.Quantity `json:"cpu"`
	// Memory is the requested memory per node (e.g. "32Gi", "32GB").
	Memory resource.Quantity `json:"memory"`
}

// ResourceReason narrows why a ResourceStatus has its current Phase. It is
// generated by the operator (not derived from R) and answers "what is
// stopping this resource from being Ready" or "what state is the operator
// driving toward".
// +kubebuilder:validation:Enum=WaitingForDependencies;Creating;Provisioning;Ready;Failed;Deleting
type ResourceReason string

const (
	// ReasonWaitingForDependencies — at least one dependsOn predecessor is
	// not yet Ready. Message names the blockers (e.g. "waiting on: cp").
	ReasonWaitingForDependencies ResourceReason = "WaitingForDependencies"
	// ReasonCreating — R exists on the target cluster but has not yet
	// surfaced a Ready signal.
	ReasonCreating ResourceReason = "Creating"
	// ReasonProvisioning — R reports an in-progress state (e.g. Gardener
	// lastOperation.state=Processing).
	ReasonProvisioning ResourceReason = "Provisioning"
	// ReasonReady — R reports Ready / Succeeded.
	ReasonReady ResourceReason = "Ready"
	// ReasonFailed — R reports a terminal failure.
	ReasonFailed ResourceReason = "Failed"
	// ReasonDeleting — SC has DeletionTimestamp set; cascade in flight.
	ReasonDeleting ResourceReason = "Deleting"
)

// ResourceStatus mirrors the live state of one node in the SCPC's DAG into SC.
// For repeated ResourceSpecs (ResourceSpec.Repeat set) the per-index detail
// lives in Instances and the top-level Phase/Reason/Message is the aggregate.
type ResourceStatus struct {
	// Name matches ResourceSpec.Name.
	Name string `json:"name"`
	// GVK is the resolved GroupVersionKind of R.
	// +optional
	GVK string `json:"gvk,omitempty"`
	// TargetName is the name of R on the target cluster. Empty when the
	// ResourceSpec is repeated; see Instances for per-index names.
	// +optional
	TargetName string `json:"targetName,omitempty"`
	// TargetNamespace is the namespace of R on the target cluster.
	// +optional
	TargetNamespace string `json:"targetNamespace,omitempty"`
	// Phase is this resource's coarse state. For repeated specs it is
	// aggregated across Instances (Ready iff all instances Ready; Failed
	// if any instance Failed; otherwise Provisioning/Pending).
	// +optional
	Phase Phase `json:"phase,omitempty"`
	// Reason is the operator's per-resource state code, narrowing Phase.
	// +optional
	Reason ResourceReason `json:"reason,omitempty"`
	// Message is the operator's human-readable detail for Reason
	// (e.g. "waiting on: cp, service").
	// +optional
	Message string `json:"message,omitempty"`
	// LastOperation mirrors a human-readable progress string from R itself.
	// +optional
	LastOperation string `json:"lastOperation,omitempty"`
	// LastError mirrors a human-readable error string from R itself.
	// +optional
	LastError string `json:"lastError,omitempty"`
	// Instances lists per-index state when the ResourceSpec is repeated.
	// Empty for non-repeated ResourceSpecs.
	// +listType=map
	// +listMapKey=index
	// +optional
	Instances []InstanceStatus `json:"instances,omitempty"`
}

// InstanceStatus is one R-object's state when its ResourceSpec is repeated.
type InstanceStatus struct {
	// Index is the 0-based iteration this entry tracks.
	Index int32 `json:"index"`
	// TargetName is the name of this R-object on the target cluster.
	TargetName string `json:"targetName"`
	// TargetNamespace is the namespace of this R-object.
	// +optional
	TargetNamespace string `json:"targetNamespace,omitempty"`
	// Phase is this instance's coarse state.
	// +optional
	Phase Phase `json:"phase,omitempty"`
	// LastOperation mirrors a human-readable progress string from R.
	// +optional
	LastOperation string `json:"lastOperation,omitempty"`
	// LastError mirrors a human-readable error string from R.
	// +optional
	LastError string `json:"lastError,omitempty"`
}

// NodeStatus is one node of the provisioned cluster (NC), read live over the
// synced kubeconfig. Surfaced so users can see the cluster's machines and how
// to reach them without fetching the kubeconfig themselves.
type NodeStatus struct {
	// Name is the Kubernetes node name.
	Name string `json:"name"`
	// Role is "control-plane" or "worker", derived from the node's role labels.
	// +optional
	Role string `json:"role,omitempty"`
	// ExternalIP is the node's ExternalIP address. Empty when the cluster does
	// not advertise one (e.g. nodes only reachable on a private network).
	// +optional
	ExternalIP string `json:"externalIP,omitempty"`
	// InternalIP is the node's InternalIP address.
	// +optional
	InternalIP string `json:"internalIP,omitempty"`
	// Ready reflects the node's Ready condition.
	Ready bool `json:"ready"`
}

// SimpleClusterStatus defines the observed state of SimpleCluster.
type SimpleClusterStatus struct {
	// ProviderConfigRef is locked at first reconcile so SCPC changes do not
	// migrate resources mid-flight.
	// +optional
	ProviderConfigRef *corev1.LocalObjectReference `json:"providerConfigRef,omitempty"`

	// TargetCluster identifies where the resources live: SCPC name (for remote)
	// or "local".
	// +optional
	TargetCluster string `json:"targetCluster,omitempty"`

	// Resources is per-ResourceSpec status, keyed by Name. Populated as the
	// DAG progresses.
	// +listType=map
	// +listMapKey=name
	// +optional
	Resources []ResourceStatus `json:"resources,omitempty"`

	// Phase is the aggregate state machine across Resources:
	//   Ready        - every Resource is Ready.
	//   Failed       - at least one Resource is Failed.
	//   Provisioning - otherwise (at least one is not yet Ready).
	//   Deleting     - SC.deletionTimestamp set.
	// +optional
	Phase Phase `json:"phase,omitempty"`

	// KubeconfigSecretRef points at the Secret in SC.namespace holding NC's kubeconfig.
	// +optional
	KubeconfigSecretRef *corev1.LocalObjectReference `json:"kubeconfigSecretRef,omitempty"`
	// KubeconfigIssuedAt is the issuance time of the embedded credential.
	// +optional
	KubeconfigIssuedAt *metav1.Time `json:"kubeconfigIssuedAt,omitempty"`
	// KubeconfigExpiresAt is the expiry time of the embedded credential.
	// +optional
	KubeconfigExpiresAt *metav1.Time `json:"kubeconfigExpiresAt,omitempty"`

	// Kubeconfig is the raw NC kubeconfig, mirrored from the Secret referenced
	// by KubeconfigSecretRef. It is duplicated here so the generic portal
	// detail view (which can only read fields of the SimpleCluster itself, not
	// a separate Secret) can surface it for copy/download. It is readable by
	// anyone with get access to this SimpleCluster — the same audience that can
	// already read the Secret in the account namespace.
	// +optional
	Kubeconfig string `json:"kubeconfig,omitempty"`

	// CP is "<readyControlPlanes>/<declaredControlPlanes>" — surfaced
	// as the CP printer column (e.g. "1/3"). "-/-" when the SCPC owns
	// the control plane (spec.controlPlane is omitted).
	// +optional
	CP string `json:"cp,omitempty"`

	// WKR is "<readyWorkers>/<declaredWorkers>" — surfaced as the
	// WKR printer column (e.g. "0/2").
	// +optional
	WKR string `json:"wkr,omitempty"`

	// Nodes lists the control-plane and worker nodes of the provisioned
	// cluster (NC) with their addresses, read live over the synced kubeconfig.
	// Populated best-effort once the kubeconfig is available; empty until then
	// and never affects Phase.
	// +listType=map
	// +listMapKey=name
	// +optional
	Nodes []NodeStatus `json:"nodes,omitempty"`

	// NodesSummary is a human-readable, one-line-per-node rendering of Nodes.
	// It exists only because the Platform Mesh generic detail view can render
	// a scalar string field but not an array of objects; the structured data
	// lives in Nodes. Derived from Nodes every reconcile.
	// +optional
	NodesSummary string `json:"nodesSummary,omitempty"`

	// +optional
	ObservedGeneration int64 `json:"observedGeneration,omitempty"`

	// +listType=map
	// +listMapKey=type
	// +optional
	Conditions []metav1.Condition `json:"conditions,omitempty"`
}

